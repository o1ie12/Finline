#!/usr/bin/env bash
# Regenerate supabase/schema.sql (and supabase/seed-lines.sql) from the
# migration history.
#
# Builds a throwaway Postgres cluster in a temp dir on its own port and
# socket, applies schema-legacy.sql and then every forward migration in
# number order, and dumps the result: the schema without data, plus the rows
# of the one reference table a fresh database cannot work without (lines).
# It never touches a running server, the local dev database or Supabase.
#
# Usage: supabase/local/build-schema.sh
# Env:   PGBIN (default /opt/homebrew/bin), PORT (default 55433)
set -euo pipefail

PGBIN="${PGBIN:-/opt/homebrew/bin}"
PORT="${PORT:-55433}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPA="$(dirname "$HERE")"
# /tmp, not $TMPDIR: macOS caps a socket path near 104 bytes.
TMP="$(mktemp -d /tmp/finline-schema.XXXXXX)"
DB=schema_build
PSQL="$PGBIN/psql -X -q -v ON_ERROR_STOP=1 -h $TMP -p $PORT -U postgres -d $DB"
export PGCLIENTENCODING=UTF8
export PGOPTIONS="-c client_min_messages=warning"

cleanup() {
  if [ -f "$TMP/data/postmaster.pid" ]; then
    "$PGBIN/pg_ctl" -D "$TMP/data" -m fast -w stop >/dev/null 2>&1 || true
  fi
  rm -rf "$TMP"
}
trap cleanup EXIT

"$PGBIN/initdb" -D "$TMP/data" -U postgres -A trust -E UTF8 --no-locale >/dev/null
LC_ALL=C "$PGBIN/pg_ctl" -D "$TMP/data" -l "$TMP/server.log" \
  -o "-p $PORT -k $TMP -c listen_addresses=''" -w start >/dev/null \
  || { cat "$TMP/server.log"; exit 1; }
"$PGBIN/createdb" -h "$TMP" -p "$PORT" -U postgres "$DB"

echo "applying schema-legacy.sql"
$PSQL -f "$SUPA/schema-legacy.sql" >/dev/null

# Forward migrations only, in number order: no -down files, no -verify checks.
APPLIED=()
for f in $(ls "$SUPA" | grep -E '^migration-[0-9]{2}-.*\.sql$' | grep -vE -- '-(down|verify)\.sql$' | sort); do
  echo "applying $f"
  $PSQL -f "$SUPA/$f" >/dev/null
  APPLIED+=("$f")
done
LAST="${APPLIED[${#APPLIED[@]}-1]}"

TABLES="$($PSQL -At -c "select string_agg(tablename, ', ' order by tablename) from pg_tables where schemaname='public';")"
NO_RLS="$($PSQL -At -c "select coalesce(string_agg(c.relname, ', ' order by c.relname), 'none') from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r' and not c.relrowsecurity;")"
echo "tables: $TABLES"
echo "tables without row level security: $NO_RLS"
echo "rows per table:"
$PSQL -At -c "select format('  %s: %s', c.relname, (xpath('/row/n/text()', query_to_xml(format('select count(*) as n from public.%I', c.relname), false, true, '')))[1]::text) from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r' order by c.relname;"

# pg_dump's \restrict lines are psql commands: the Supabase SQL editor does not take them.
dump() { "$PGBIN/pg_dump" -h "$TMP" -p "$PORT" -U postgres -d "$DB" --no-owner --no-privileges "$@" | grep -vE '^\\(un)?restrict ' ; }

{
  cat <<HEADER
-- Finline (錢途): the whole database schema, for a new, empty database.
--
-- GENERATED by supabase/local/build-schema.sh. Do not edit by hand: change
-- the schema with a new migration file, then run that script again.
-- State: schema-legacy.sql plus every migration through $LAST.
--
-- A new database needs three things, in this order (supabase/README.md):
--   1. this file
--   2. supabase/seed-lines.sql   (the 12 courses; other tables point at them)
--   3. npx tsx scripts/seed-historical-prices.ts   (prices for the replay simulator)
--
-- Every table has row level security ON with no policies: only the server
-- (the service role key, which bypasses RLS) reads or writes. Nothing in a
-- browser talks to the database.

HEADER
  dump --schema-only
} > "$SUPA/schema.sql"

{
  cat <<HEADER
-- Finline (錢途): the rows of public.lines, the one reference table.
--
-- GENERATED by supabase/local/build-schema.sh from the migrations that
-- insert and rename lines. Run it once on a new database, after schema.sql.
-- lines.slug and lines.id are what simulation_runs, line_tests, class_rooms
-- and line_completions point at; without these rows their inserts fail.

HEADER
  dump --data-only --column-inserts --table=public.lines
} > "$SUPA/seed-lines.sql"

# Prove the two files stand on their own: load them into a second, empty
# database and compare its schema with the one the migrations built.
"$PGBIN/createdb" -h "$TMP" -p "$PORT" -U postgres schema_verify
VERIFY="$PGBIN/psql -X -q -v ON_ERROR_STOP=1 -h $TMP -p $PORT -U postgres -d schema_verify"
$VERIFY -f "$SUPA/schema.sql" >/dev/null
$VERIFY -f "$SUPA/seed-lines.sql" >/dev/null
"$PGBIN/pg_dump" -h "$TMP" -p "$PORT" -U postgres -d schema_verify --no-owner --no-privileges --schema-only | grep -vE '^\\(un)?restrict ' > "$TMP/verify.sql"
dump --schema-only > "$TMP/built.sql"
if diff -q "$TMP/built.sql" "$TMP/verify.sql" >/dev/null && [ "$($VERIFY -At -c 'select count(*) from public.lines')" = "$($PSQL -At -c 'select count(*) from public.lines')" ]; then
  echo "verified: schema.sql + seed-lines.sql rebuild the same schema on an empty database"
else
  echo "MISMATCH: an empty database built from schema.sql differs from the migrations" >&2
  diff "$TMP/built.sql" "$TMP/verify.sql" | head -20 >&2
  exit 1
fi

echo "wrote supabase/schema.sql ($(wc -l < "$SUPA/schema.sql" | tr -d ' ') lines) and supabase/seed-lines.sql"
